/** t('uz', 'btnRegister') — matn olish */
export function t(lang: string, key: string): string {
  const set = translations[lang] || translations.uz;
  return set[key] !== undefined ? set[key] : translations.uz[key] !== undefined ? translations.uz[key] : key;
}

/** {name} kabi o'zgartiruvchilarni joylash: tf('uz', 'registered', { name: 'Ali' }) */
export function tf(lang: string, key: string, vars: Record<string, any> = {}): string {
  let text = t(lang, key);
  for (const [k, v] of Object.entries(vars)) {
    text = text.split(`{${k}}`).join(String(v));
  }
  return text;
}
